// Writes the length tables `wordLengthRange`, `nicknameLengthRange` and
// `sentenceLengthRange` read, out of the pools and the frames the generators
// draw from. `index.mjs` runs it and formats what it wrote; see
// `tools/lengths/README.md`.

import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { frameSpans } from '../../packages/javascript/lib/nickname/nicknameGenerator.js';
import { naturalRange as sentenceRange } from '../../packages/javascript/lib/sentence/sentenceGenerator.js';
import {
	WORD_DATA,
	WORD_LANGUAGES,
	WORD_THEMES
} from '../../packages/javascript/lib/word/data/index.js';
import { naturalRange as wordRange } from '../../packages/javascript/lib/word/wordGenerator.js';

const LIB = resolve(dirname(fileURLToPath(import.meta.url)), '../../packages/javascript/lib');
const GENERATED = [
	'// Generated by `tools/lengths` from the pools and the frames. Do not edit by',
	'// hand; regenerate instead.'
];

/** A table entry as TypeScript reads it: JSON is close enough, and prettier tidies the rest. */
const literal = (value: unknown) => JSON.stringify(value);

function writeWords() {
	const words = WORD_LANGUAGES.map((code) => {
		const themes = WORD_THEMES.map((theme) => `\t\t${theme}: ${literal(wordRange(code, theme))},`);

		return [`\t${code}: {`, ...themes, '\t},'].join('\n');
	});
	const nicknames = WORD_LANGUAGES.map(
		(code) =>
			`\t${code}: { joiner: ${literal(WORD_DATA[code].joiner)}, spans: ${literal(frameSpans(code))} },`
	);
	const body = [
		...GENERATED,
		'//',
		'// The lengths the word pools and the nickname shapes span, kept apart from',
		'// them so that `wordLengthRange` and `nicknameLengthRange` bundle without a',
		'// pool. `test/word.test.ts` and `test/nickname.test.ts` fail when a pool moves',
		'// one of them.',
		'',
		"import type { WordLanguage, WordTheme } from '../../_types/global.js';",
		'',
		'/** The shortest and longest noun of every theme, per language. */',
		'export const WORD_LENGTHS: Record<WordLanguage, Record<WordTheme, readonly [number, number]>> = {',
		...words,
		'};',
		'',
		'/**',
		" * Each language's own joiner, and its nickname shapes' shortest and longest",
		' * by how many gaps they have between their words: `spans[n]` is the shapes of',
		" * `n + 1` words, with nothing in a gap but the frame's particle. A joiner adds",
		' * its length once per gap.',
		' */',
		'export const NICKNAME_SPANS: Record<',
		'\tWordLanguage,',
		'\t{ joiner: string; spans: readonly (readonly [number, number])[] }',
		'> = {',
		...nicknames,
		'};',
		''
	];

	writeFileSync(resolve(LIB, 'word/data/lengths.ts'), body.join('\n'));
}

function writeSentences() {
	const sentences = WORD_LANGUAGES.map((code) => `\t${code}: ${literal(sentenceRange(code))},`);
	const body = [
		...GENERATED,
		'//',
		"// The shortest and longest sentence each language's shapes can write, kept",
		'// apart from the pools so that `sentenceLengthRange` bundles without them.',
		'// `test/sentence.test.ts` fails when a pool or a shape moves one of them.',
		'',
		"import type { WordLanguage } from '../../_types/global.js';",
		'',
		'export const SENTENCE_LENGTHS: Record<WordLanguage, readonly [number, number]> = {',
		...sentences,
		'};',
		''
	];

	writeFileSync(resolve(LIB, 'sentence/data/lengths.ts'), body.join('\n'));
}

writeWords();
writeSentences();
