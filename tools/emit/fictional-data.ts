// Emits the Dart and Python fictional datasets from the JavaScript ones, so the
// three packages hold the same tables. `index.mjs` runs it and formats what it
// wrote; see `tools/emit/README.md`.
//
// Every fictional dataset is a table written as one string, so a port's copy is
// the same string in its own syntax and nothing has to be translated on the way.

