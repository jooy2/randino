const GENERATED =
	"Generated by `tools/emit` from the JavaScript package, which is where it is edited.";

function source(name: Table["js"]): string {
	const text = DATA[name];

	if (typeof text !== "string" || text.includes("'''") || text.includes('"""')) {
		throw new Error(`${name} is not a table the ports can hold as a raw string`);
	}

	return text;
}

function emitDart(module: Module): string {
	const tables = module.tables
		.map((table) => `/// ${table.doc}\nconst String ${table.dart} = r'''${source(table.js)}''';\n`)
		.join("\n");

	return `// ${module.summary}\n//\n// ${GENERATED}\n\n${tables}`;
}

function emitPython(module: Module): string {
	const tables = module.tables
		.map((table) => `${table.js} = r"""${source(table.js)}"""\n"""${table.doc}"""\n`)
		.join("\n");

	return `"""${module.summary}\n\n${GENERATED}\n"""\n\n${tables}`;
}

for (const module of MODULES) {
	writeFileSync(`${ROOT}/dart/lib/src/fictional/data/${module.file}.dart`, emitDart(module));
	writeFileSync(`${ROOT}/python/src/randino/fictional/data/${module.file}.py`, emitPython(module));
}
