"""The module each name of `__all__` comes from."""


def __getattr__(name: str) -> object:
    """Import the module `name` comes from the first time it is asked for, and keep it.

    Args:
        name: A name of `__all__`.

    Returns:
        What the name is.

    Raises:
        AttributeError: For a name the package does not export.
    """
    home = _HOMES.get(name)

    if home is None:
        raise AttributeError(f"module 'randino' has no attribute {name!r}")

    value = getattr(importlib.import_module(home), name)
    globals()[name] = value

    return value


def __dir__() -> list[str]:
    """The names `__all__` exports, which is what the module holds once they are read."""
    return sorted(__all__)
